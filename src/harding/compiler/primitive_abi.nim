import std/tables

type PrimitiveBinding* = object
  nimProc*: string

proc extendPrimitiveBindings(bindings: var Table[string, PrimitiveBinding])

proc nativePrimitiveBindings*(): Table[string, PrimitiveBinding] =
  ## Primitive selector -> Nim implementation. This is the one boundary between
  ## compiled Harding method bodies and the representations they operate on: a
  ## selector named by a `<primitive ...>` declaration must appear here, and
  ## everything else in that position is reported as a compilation gap rather
  ## than implemented as a second version of a Harding method.
  result = initTable[string, PrimitiveBinding]()
  for (selector, target) in [
    # Text and value conversion.
    ("primitiveAsInteger", "primitiveAsInteger"),
    ("primitiveAsFloat", "primitiveAsFloat"),
    ("primitiveStringSize", "primitiveStringSizeValueImpl"),
    ("primitiveConcat:", "primitiveStringConcatValueImpl"),
    ("primitiveStringAt:", "primitiveStringAtValueImpl"),
    ("primitiveLowercase", "primitiveStringLowercaseValueImpl"),
    ("primitiveUppercase", "primitiveStringUppercaseValueImpl"),
    ("primitiveTrim", "primitiveStringTrimValueImpl"),
    ("primitiveSplit:", "primitiveStringSplitValueImpl"),
    ("primitiveFromTo:to:", "primitiveStringFromToValueImpl"),
    ("primitiveIndexOf:", "primitiveStringIndexOfValueImpl"),
    ("primitiveIncludesSubString:", "primitiveStringIncludesSubStringValueImpl"),
    ("primitiveReplaceWith:with:", "primitiveStringReplaceWithValueImpl"),
    ("primitiveAsSymbol", "primitiveStringAsSymbolValueImpl"),
    ("primitiveRepeat:", "primitiveStringRepeatValueImpl"),
    ("primitiveStringAppend:", "primitiveStringAppendValueImpl"),
    ("primitiveStartsWith:", "primitiveStartsWithValueImpl"),
    ("primitiveEndsWith:", "primitiveEndsWithValueImpl"),
    ("primitivePrintString", "primitivePrintStringValueImpl"),
    # Array.
    ("primitiveArrayNew", "primitiveArrayNew"),
    ("primitiveArrayNew:", "primitiveArrayNewSize"),
    ("primitiveArrayNew:withAll:", "primitiveArrayNewSizeWithAll"),
    ("primitiveArraySize", "primitiveArraySize"),
    ("primitiveArrayAt:", "primitiveArrayAt"),
    ("primitiveArrayAt:put:", "primitiveArrayAtPut"),
    ("primitiveArrayAdd:", "primitiveArrayAdd"),
    ("primitiveArrayRemoveAt:", "primitiveArrayRemoveAt"),
    ("primitiveArrayRemoveAll", "primitiveArrayRemoveAll"),
    ("primitiveArrayIncludes:", "primitiveArrayIncludes"),
    ("primitiveArrayReverse", "primitiveArrayReverse"),
    # Table.
    ("primitiveTableNew", "primitiveTableNew"),
    ("primitiveTableAt:", "primitiveTableAt"),
    ("primitiveTableAt:put:", "primitiveTableAtPut"),
    ("primitiveKeys", "primitiveTableKeys"),
    ("primitiveIncludesKey:", "primitiveTableIncludesKey"),
    ("primitiveRemoveKey:", "primitiveTableRemoveKey"),
    # Set.
    ("primitiveSetNew", "primitiveSetNew"),
    ("primitiveSetAdd:", "primitiveSetAdd"),
    ("primitiveSetRemove:", "primitiveSetRemove"),
    ("primitiveSetIncludes:", "primitiveSetIncludes"),
    ("primitiveSetSize", "primitiveSetSize"),
    ("primitiveSetAsArray", "primitiveSetAsArray"),
    ("primitiveSetUnion:", "primitiveSetUnion"),
    ("primitiveSetIntersection:", "primitiveSetIntersection"),
    ("primitiveSetDifference:", "primitiveSetDifference")]:
    result[selector] = PrimitiveBinding(nimProc: target)
  extendPrimitiveBindings(result)

