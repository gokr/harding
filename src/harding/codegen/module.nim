proc genModuleHeader*(ctx: var CompilerContext, moduleName: string,
                      includeOsImport: bool = false): string =
  ## Generate module header with imports and documentation
  var output = ""

  output.add("## Generated by Harding Compiler\n")
  output.add("## Module: " & moduleName & "\n")
  output.add("## Do not edit - generated from .hrd source\n\n")

  output.add("# Imports\n")
  if includeOsImport:
    output.add("import std/[tables, sequtils, os]\n")
  else:
    output.add("import std/[tables, sequtils]\n")
  let sourceRoot = parentDir(parentDir(parentDir(currentSourcePath())))
  let importRoot = relativePath(sourceRoot, absolutePath(ctx.outputDir)).replace('\\', '/')
  output.add(fmt("import {importRoot}/harding/runtime/compiled_support\n\n"))
  if ctx.gtkApplication:
    output.add(fmt("import {importRoot}/harding/gui/gtk/native_application\n\n"))

  return output


proc nativeSlotType(slot: SlotDef): string =
  ## Native Nim type for a declared primitive slot; "" keeps NodeValue.
  case slot.constraint
  of tcInt: "int"
  of tcFloat: "float64"
  of tcBool: "bool"
  of tcString, tcSymbol: "string"
  else: ""

proc boxExpression(slot: SlotDef, source: string): string =
  ## Wrap a native field value as a NodeValue for the accessor boundary.
  case slot.constraint
  of tcInt: fmt("NodeValue(kind: vkInt, intVal: {source})")
  of tcFloat: fmt("NodeValue(kind: vkFloat, floatVal: {source})")
  of tcBool: fmt("NodeValue(kind: vkBool, boolVal: {source})")
  of tcString: fmt("NodeValue(kind: vkString, strVal: {source})")
  of tcSymbol: fmt("NodeValue(kind: vkSymbol, symVal: {source})")
  else: source

proc unboxExpression(slot: SlotDef, source: string): string =
  ## Read a native value out of a NodeValue argument, with a checked fallback so
  ## a wrong kind is a Harding error rather than a silent reinterpretation.
  case slot.constraint
  of tcInt: fmt("compiledSlotInt({source})")
  of tcFloat: fmt("compiledSlotFloat({source})")
  of tcBool: fmt("compiledSlotBool({source})")
  of tcString: fmt("compiledSlotString({source})")
  of tcSymbol: fmt("compiledSlotSymbol({source})")
  of tcObject:
    if slot.objectClass.len > 0: fmt("checkedCompiledSlot({source}, scObject, \"{slot.objectClass}\")")
    else: source
  else: source

proc genClassConstants*(cls: ClassInfo): string =
  ## Generate native Nim type for Harding class with slot accessors
  let clsName = mangleClass(cls.name)
  let slots = cls.getAllSlots()
  
  # Keep generated native objects rooted at HardingObject.
  # Language-level inheritance is handled by runtime method dispatch tables.
  let parentName = "HardingObject"
  
  var output = fmt("# {cls.name} Class\n")
  output.add("###################\n\n")
  
  # Generate Nim object type with slots as fields
  # TODO: Eventually when we generate native methods directly, we can remove
  # classRef and toValue() - methods will be called directly instead of via sendMessage
  output.add("type\n")
  output.add(fmt("  {clsName}Obj* {{.inheritable.}} = object of {parentName}\n"))
  output.add(fmt("    classRef*: Class  ## Store class reference for toValue() (temporary - see above)\n"))
  
  # Slot fields - include inherited slots so each native class is self-contained
  for slot in slots:
    let slotName = mangleSlot(slot.name)
    let nativeType = nativeSlotType(slot)
    let fieldType = if nativeType.len > 0: nativeType else: "NodeValue"
    output.add(fmt("    {slotName}*: {fieldType}\n"))
  
  output.add(fmt("  {clsName}* = ref {clsName}Obj\n\n"))
  
  # Constructor
  output.add(fmt("proc new{clsName}*(): {clsName} =\n"))
  output.add(fmt("  ## Create new {cls.name} instance\n"))
  output.add(fmt("  result = {clsName}(new({clsName}Obj))\n"))
  output.add(fmt("  result.className = \"{cls.name}\"\n"))
  output.add(fmt("  registerNimProxyClassName(cast[pointer](result), \"{cls.name}\")\n"))
  # Get class reference from interpreter globals (temporary workaround)
  # This registers the class so toValue() can create proper Instance wrapper
  output.add(fmt("  if hybridInterpreter != nil:\n"))
  output.add(fmt("    if \"{cls.name}\" in hybridInterpreter.globals[]:\n"))
  output.add(fmt("      let clsVal = hybridInterpreter.globals[][\"{cls.name}\"]\n"))
  output.add(fmt("      if clsVal.kind == vkClass:\n"))
  output.add(fmt("        result.classRef = clsVal.classVal\n"))
  output.add(fmt("      elif clsVal.kind == vkInstance and clsVal.instVal != nil:\n"))
  output.add(fmt("        result.classRef = clsVal.instVal.class\n"))
  output.add(fmt("    elif \"Object\" in hybridInterpreter.globals[]:\n"))
  output.add(fmt("      let objVal = hybridInterpreter.globals[][\"Object\"]\n"))
  output.add(fmt("      if objVal.kind == vkInstance and objVal.instVal != nil:\n"))
  output.add(fmt("        result.classRef = objVal.instVal.class\n"))
  output.add(fmt("  if result.classRef == nil:\n"))
  output.add(fmt("    result.classRef = compiledClassValue(\"{cls.name}\").classVal\n"))
  for slot in slots:
    if slot.defaultValue.len > 0:
      # A declared default (`#{#x -> 0}`) must match the interpreter exactly.
      output.add(fmt("  result.{mangleSlot(slot.name)} = {slot.defaultValue}\n"))
    else:
      let zero = case slot.constraint
        of tcInt: "0"
        of tcFloat: "0.0"
        of tcBool: "false"
        of tcString, tcSymbol: "\"\""
        else: "NodeValue(kind: vkNil)"
      output.add(fmt("  result.{mangleSlot(slot.name)} = {zero}\n"))
  output.add("\n")

  # toValue - convert native type to NodeValue using stored classRef
  # TODO: Remove when native method generation is complete
  output.add(fmt("proc toValue*(self: {clsName}): NodeValue =\n"))
  output.add(fmt("  ## Convert {cls.name} to NodeValue for sendMessage interop\n"))
  output.add(fmt("  let inst = Instance(kind: ikObject, class: self.classRef, isNimProxy: true, compiledOwner: self)\n"))
  output.add("  inst.nimValue = cast[pointer](self)\n")
  output.add(fmt("  return NodeValue(kind: vkInstance, instVal: inst)\n"))
  output.add("\n")
  
  return output

proc genClassInit*(cls: ClassInfo): string =
  ## Generate class initialization procedure (legacy - kept for compatibility)
  let clsName = mangleClass(cls.name)
  
  return fmt("""
# Legacy class init - use new{clsName}() constructor instead
# proc init_{clsName}*(): {clsName} = new{clsName}()

""")

proc inheritedSlotPermissions*(cls: ClassInfo, readable: bool): seq[string] =
  ## Parent-first slot permissions, matching newClass inheritance order.
  if cls == nil:
    return @[]
  if cls.parent != nil:
    result = inheritedSlotPermissions(cls.parent, readable)
  for name in (if readable: cls.getterSlots else: cls.setterSlots):
    if name notin result:
      result.add(name)

proc genSlotAccessors*(cls: ClassInfo): string =
  ## Generate native Nim slot accessor procs for a class
  let clsName = mangleClass(cls.name)
  let slots = cls.getAllSlots()

  var output = ""
  if slots.len == 0:
    return output

  output.add("# Slot accessors\n")
  output.add("################################\n\n")

  for slot in slots:
    if slot.isInherited:
      continue
    let slotName = mangleSlot(slot.name)

    # Typed getter
    output.add(fmt("proc get{slotName}*(self: {clsName}): NodeValue =\n"))
    output.add(fmt("  ## Get slot '{slot.name}' from {cls.name}\n"))
    let boxed = boxExpression(slot, fmt("self[].{slotName}"))
    output.add(fmt("  return {boxed}\n\n"))

    # Typed setter
    output.add(fmt("proc set{slotName}*(self: {clsName}, value: NodeValue): NodeValue =\n"))
    output.add(fmt("  ## Set slot '{slot.name}' on {cls.name}\n"))
    let unboxed = unboxExpression(slot, "value")
    output.add(fmt("  self[].{slotName} = {unboxed}\n"))
    output.add(fmt("  return value\n\n"))

  # Each native class has its own full layout, including inherited fields.
  # Proc names embed the mangled class name: raw spellings such as FooBar/Foobar
  # collapse under Nim's style-insensitive comparison and would redefine procs.
  for slot in slots:
    let slotName = mangleSlot(slot.name)
    output.add(fmt("proc slotGet_{clsName}_{slotName}(nimValue: pointer): NodeValue {{.nimcall.}} =\n"))
    let boxedPtr = boxExpression(slot, fmt("cast[{clsName}](nimValue)[].{slotName}"))
    output.add(fmt("  return {boxedPtr}\n\n"))
    output.add(fmt("proc slotSet_{clsName}_{slotName}(nimValue: pointer, value: NodeValue): NodeValue {{.nimcall.}} =\n"))
    let unboxedPtr = unboxExpression(slot, "value")
    output.add(fmt("  cast[{clsName}](nimValue)[].{slotName} = {unboxedPtr}\n"))
    output.add(fmt("  return value\n\n"))

  for slot in slots:
    let field = mangleSlot(slot.name)
    let prefix = mangleClass(cls.name) & "_direct_" & field
    output.add(fmt("var {prefix}_version {{.threadvar.}}: uint64\n"))
    output.add(fmt("var {prefix}_valid {{.threadvar.}}: bool\n"))
    output.add(fmt("proc {prefix}_guard(self: NodeValue): bool {{.inline.}} =\n"))
    output.add(fmt("  if {prefix}_version != compiledSlotAccessorVersion:\n"))
    output.add(fmt("    {prefix}_valid = slotGetters.getOrDefault(\"{cls.name}::{slot.name}\") == slotGet_{clsName}_{field} and slotSetters.getOrDefault(\"{cls.name}::{slot.name}\") == slotSet_{clsName}_{field}\n"))
    output.add(fmt("    {prefix}_version = compiledSlotAccessorVersion\n"))
    output.add(fmt("  {prefix}_valid and self.kind == vkInstance and self.instVal != nil and self.instVal.kind == ikObject and self.instVal.isNimProxy and self.instVal.nativeSlots == nil and self.instVal.compiledOwner != nil and self.instVal.compiledOwner of {clsName} and self.instVal.nimValue == cast[pointer](self.instVal.compiledOwner) and self.instVal.class != nil and self.instVal.class.name == \"{cls.name}\"\n\n"))
    output.add(fmt("proc {prefix}_read(self: NodeValue): NodeValue {{.inline.}} =\n"))
    let directRead = boxExpression(slot, fmt("{clsName}(self.instVal.compiledOwner)[].{field}"))
    output.add(fmt("  if {prefix}_guard(self): return {directRead}\n"))
    output.add(fmt("  getSlotValue(self, \"{slot.name}\")\n\n"))
    output.add(fmt("proc {prefix}_write(self: NodeValue, value: NodeValue): NodeValue {{.inline.}} =\n"))
    output.add(fmt("  if {prefix}_guard(self):\n"))
    let directWrite = unboxExpression(slot, "value")
    output.add(fmt("    {clsName}(self.instVal.compiledOwner)[].{field} = {directWrite}\n"))
    output.add("    return value\n")
    output.add(fmt("  setSlotValue(self, \"{slot.name}\", value)\n\n"))

  for slotName in cls.getterSlots:
    let mangledSlot = mangleSlot(slotName)
    output.add(fmt("proc methodGet_{clsName}_{mangledSlot}(self: NodeValue, args: seq[NodeValue]): NodeValue =\n"))
    output.add(fmt("  {clsName}_direct_{mangledSlot}_read(self)\n\n"))
  for slotName in cls.setterSlots:
    let mangledSlot = mangleSlot(slotName)
    output.add(fmt("proc methodSet_{clsName}_{mangledSlot}(self: NodeValue, args: seq[NodeValue]): NodeValue =\n"))
    output.add(fmt("  discard {clsName}_direct_{mangledSlot}_write(self, args[0])\n"))
    output.add("  self\n\n")

  return output

proc genSlotAccessorRegistrations*(cls: ClassInfo): string =
  ## Generate registerSlotAccessor calls for a class
  let slots = cls.getAllSlots()
  let clsName = mangleClass(cls.name)
  var output = ""
  let names = slots.mapIt("\"" & it.name & "\"").join(", ")
  output.add(fmt("  registerCompiledSlotNames(\"{cls.name}\", @[{names}])\n"))
  for slot in slots:
    let contractKind = case slot.constraint
      of tcInt: "scInteger"
      of tcFloat: "scFloat"
      of tcBool: "scBoolean"
      of tcString: "scString"
      of tcSymbol: "scSymbol"
      of tcObject:
        if slot.objectClass.len > 0: "scObject" else: "scDynamic"
      else: "scDynamic"
    output.add(fmt("  compiledClassValue(\"{cls.name}\").classVal.slotContracts[\"{slot.name}\"] = SlotContract(kind: {contractKind})\n"))
    if slot.objectClass.len > 0:
      output.add(fmt("  compiledClassValue(\"{cls.name}\").classVal.slotContracts[\"{slot.name}\"].objectType = ensureCompiledClass(\"{slot.objectClass}\")\n"))
    if slot.defaultValue.len > 0:
      let literal = case slot.constraint
        of tcInt: fmt("NodeValue(kind: vkInt, intVal: {slot.defaultValue})")
        of tcFloat: fmt("NodeValue(kind: vkFloat, floatVal: {slot.defaultValue})")
        of tcBool: fmt("NodeValue(kind: vkBool, boolVal: {slot.defaultValue})")
        of tcString: fmt("NodeValue(kind: vkString, strVal: {slot.defaultValue})")
        of tcSymbol: fmt("NodeValue(kind: vkSymbol, symVal: {slot.defaultValue})")
        else: "NodeValue(kind: vkNil)"
      output.add(fmt("  compiledClassValue(\"{cls.name}\").classVal.setSlotDefault(\"{slot.name}\", {literal})\n"))
    else:
      let initial = case slot.constraint
        of tcInt: "NodeValue(kind: vkInt, intVal: 0)"
        of tcFloat: "NodeValue(kind: vkFloat, floatVal: 0.0)"
        of tcBool: "NodeValue(kind: vkBool, boolVal: false)"
        of tcString: "NodeValue(kind: vkString, strVal: \"\")"
        of tcSymbol: "NodeValue(kind: vkSymbol, symVal: \"\")"
        else: "NodeValue(kind: vkNil)"
      output.add(fmt("  compiledClassValue(\"{cls.name}\").classVal.setSlotDefault(\"{slot.name}\", {initial})\n"))
  # Slot permissions inherit parent-first, as in newClass; dedupe by name.
  let readable = inheritedSlotPermissions(cls, true).mapIt("\"" & it & "\"").join(", ")
  let writable = inheritedSlotPermissions(cls, false).mapIt("\"" & it & "\"").join(", ")
  output.add(fmt("  compiledClassValue(\"{cls.name}\").classVal.readableSlotNames = @[{readable}]\n"))
  output.add(fmt("  compiledClassValue(\"{cls.name}\").classVal.writableSlotNames = @[{writable}]\n"))
  for slot in slots:
    let slotName = mangleSlot(slot.name)
    output.add(fmt("  registerSlotAccessor(\"{cls.name}\", \"{slot.name}\", slotGet_{clsName}_{slotName}, slotSet_{clsName}_{slotName})\n"))
  for slotName in cls.getterSlots:
    if slotName notin cls.instanceSelectors:
      let mangledSlot = mangleSlot(slotName)
      output.add(fmt("  registerCompiledMethod(\"{cls.name}\", \"{slotName}\", methodGet_{clsName}_{mangledSlot})\n"))
  for slotName in cls.setterSlots:
    if slotName & ":" notin cls.instanceSelectors:
      let mangledSlot = mangleSlot(slotName)
      output.add(fmt("  registerCompiledMethod(\"{cls.name}\", \"{slotName}:\", methodSet_{clsName}_{mangledSlot})\n"))
  return output

proc collectAstNodes(nodes: var Table[pointer, bool], node: Node) =
  ## Record the identity of every node reachable from `node` (used to match
  ## registered blocks against the method body they were collected from)
  if node == nil:
    return
  nodes[cast[pointer](node)] = true
  case node.kind
  of nkBlock:
    for stmt in node.BlockNode.body:
      collectAstNodes(nodes, stmt)
  of nkMessage:
    let msg = node.MessageNode
    collectAstNodes(nodes, msg.receiver)
    for arg in msg.arguments:
      collectAstNodes(nodes, arg)
  of nkAssign:
    collectAstNodes(nodes, node.AssignNode.expression)
  of nkReturn:
    collectAstNodes(nodes, node.ReturnNode.expression)
  of nkIf:
    collectAstNodes(nodes, node.IfNode.condition)
    collectAstNodes(nodes, node.IfNode.thenBranch)
    collectAstNodes(nodes, node.IfNode.elseBranch)
  of nkWhile:
    collectAstNodes(nodes, node.WhileNode.condition)
    collectAstNodes(nodes, node.WhileNode.body)
  of nkArray:
    for elem in node.ArrayNode.elements:
      collectAstNodes(nodes, elem)
  of nkTable:
    for (key, value) in node.TableNode.entries:
      collectAstNodes(nodes, key)
      collectAstNodes(nodes, value)
  of nkNamedAccess:
    collectAstNodes(nodes, node.NamedAccessNode.receiver)
    collectAstNodes(nodes, node.NamedAccessNode.valueExpr)
  of nkSlotAccess:
    collectAstNodes(nodes, node.SlotAccessNode.valueExpr)
  of nkSuperSend:
    for arg in node.SuperSendNode.arguments:
      collectAstNodes(nodes, arg)
  of nkPrimitiveCall:
    for arg in node.PrimitiveCallNode.arguments:
      collectAstNodes(nodes, arg)
  of nkCascade:
    collectAstNodes(nodes, node.CascadeNode.receiver)
    for msg in node.CascadeNode.messages:
      collectAstNodes(nodes, msg)
  of nkLiteral:
    let litVal = node.LiteralNode.value
    if litVal.kind == vkBlock and litVal.blockVal != nil:
      for stmt in litVal.blockVal.body:
        collectAstNodes(nodes, stmt)
  else:
    discard

proc isClassDefinition(node: Node): bool =
  ## Check if a node is a class definition (derive: chain)
  let (className, _, _) = extractDeriveChain(node)
  return className.len > 0

proc isMethodDefinition(node: Node): bool =
  ## Check if a node is a method definition (selector:put: or classSelector:put:)
  if node.kind != nkMessage:
    return false
  let msg = node.MessageNode
  return msg.selector in ["selector:put:", "classSelector:put:"]

proc extractClassAndMethodDefs(nodes: seq[Node]): tuple[defs: seq[Node], topLevel: seq[Node]] =
  ## Separate class/method definitions from top-level executable statements
  var defs: seq[Node] = @[]
  var topLevel: seq[Node] = @[]

  for node in nodes:
    if node.isClassDefinition or node.isMethodDefinition:
      defs.add(node)
    else:
      topLevel.add(node)

  return (defs, topLevel)

proc extractMethodDefs(nodes: seq[Node]): seq[tuple[className, selector: string, params, temporaries: seq[string], body: seq[Node], methodId: int, isClassMethod: bool]] =
  ## Extract method definitions from AST nodes
  ## Returns (className, selector, params, body) for each method
  result = @[]
  
  for node in nodes:
    if node.kind == nkMessage:
      let msg = node.MessageNode
      if msg.selector in ["selector:put:", "classSelector:put:"] and msg.arguments.len >= 2:
        var bodyBlock: BlockNode = nil
        if msg.arguments[1].kind == nkBlock:
          bodyBlock = msg.arguments[1].BlockNode
        elif msg.arguments[1].kind == nkLiteral:
          let litVal = msg.arguments[1].LiteralNode.value
          if litVal.kind == vkBlock:
            bodyBlock = litVal.blockVal
        
        if msg.arguments[0].kind == nkLiteral and bodyBlock != nil:
          let litVal = msg.arguments[0].LiteralNode.value
          let selectorName = if litVal.kind == vkSymbol: litVal.symVal 
                             elif litVal.kind == vkString: litVal.strVal
                             else: ""
          
          var className = ""
          if msg.receiver != nil and msg.receiver.kind == nkIdent:
            className = msg.receiver.IdentNode.name
          
          if className.len > 0 and selectorName.len > 0:
            # Stable id per method proc, used for non-local return targeting
            let methodId = 1000 + result.len
            result.add((className, selectorName, bodyBlock.parameters, bodyBlock.temporaries, bodyBlock.body, methodId,
                        msg.selector == "classSelector:put:"))

proc collectDeclarativePrimitives*(nodes: seq[Node], unsupported: var seq[string]) =
  ## Collect declarative primitive methods (`>>sel <primitive primName>`) found in
  ## the definition nodes, described as "Class>>selector (primName)".
  ##
  ## Granite has no native implementation for these: the `.hrd` primitive form
  ## names a VM primitive installed in Nim, and the compiled runtime carries none
  ## of them. Emitting a call to a non-existent helper turned this into an
  ## unrelated Nim error inside generated code, so the call site is diagnosed
  ## here instead.
  let (defs, _) = extractClassAndMethodDefs(nodes)
  for md in extractMethodDefs(defs):
    var tag = ""
    for stmt in md.body:
      if stmt != nil and stmt.kind == nkPrimitiveCall:
        tag = stmt.PrimitiveCallNode.selector
        break
      if stmt != nil and stmt.kind == nkReturn and stmt.ReturnNode.expression != nil and
         stmt.ReturnNode.expression.kind == nkPrimitiveCall:
        tag = stmt.ReturnNode.expression.PrimitiveCallNode.selector
        break
    if tag.len > 0:
      unsupported.add(md.className & ">>" & md.selector & " (" & tag & ")")

proc unsupportedPrimitiveMessage*(names: seq[string]): string =
  ## Explain why a declarative primitive cannot be compiled natively.
  var listed = names
  if listed.len > 5:
    listed = listed[0..4]
    listed.add("...")
  "Granite cannot compile declarative primitives to native code.\n" &
    "  Not supported: " & listed.join(", ") & "\n" &
    "  These name VM primitives implemented in Nim; the compiled runtime does not\n" &
    "  provide them. Run the program with the interpreter, or compile with --mixed\n" &
    "  so those sends fall back to the VM."

proc genCompiledMethods*(methodDefs: seq[tuple[className, selector: string, params, temporaries: seq[string], body: seq[Node], methodId: int, isClassMethod: bool]],
                         compiledClasses: seq[string], classInfo: Table[string, ClassInfo],
                         blockReg: BlockRegistry = nil,
                         knownGlobals: seq[string] = @[], mixed: bool = false,
                         inferredNumeric: Table[string, string] = initTable[string, string](),
                         integerCandidates: var Table[string, string],
                         staticClassCalls: var Table[string, string]): string =
  ## Generate compiled method procs from extracted method definitions
  var output = ""
  var registrationCode = ""
  var shimBindingCode = ""
  
  if methodDefs.len == 0:
    # Generate slot accessor registrations even with no methods
    var slotRegCode = ""
    for clsName in compiledClasses:
      if clsName in classInfo:
        slotRegCode.add(genSlotAccessorRegistrations(classInfo[clsName]))
    output.add("# Method Registration\n")
    output.add("#####################\n\n")
    output.add("proc registerCompiledMethods*() =\n")
    for className in compiledClasses:
      output.add(fmt("  registerCompiledSlotNames(\"{className}\", @[])\n"))
    if slotRegCode.len > 0:
      output.add(slotRegCode)
    else:
      output.add("  discard 0\n")
    output.add("\n")
    return output
  
  var directCandidates = initTable[string, string]()
  if not mixed:
    var targets = initTable[string, seq[tuple[owner, target, slot: string]]]()
    for md in methodDefs:
      if not md.isClassMethod and md.params.len == 0 and md.className in compiledClasses:
        targets.mgetOrPut(md.selector, @[]).add((md.className,
          mangleClass(md.className) & "_" & mangleSelector(md.selector), ""))
    for name in compiledClasses:
      if name notin classInfo: continue
      let cls = classInfo[name]
      for slot in cls.getterSlots:
        if slot notin cls.instanceSelectors:
          targets.mgetOrPut(slot, @[]).add((name, "methodGet_" & mangleClass(name) & "_" & mangleSlot(slot), slot))
    for selector, choices in targets:
      if choices.len != 1 or selector in ["message", "signal", "defaultAction", "retry", "pass", "==", "~="]:
        continue
      let choice = choices[0]
      # Nim identifiers are style-insensitive: selectors that differ only in case
      # (slotValue vs slotvalue) must not share a helper name. mangleSlot uses
      # the case-safe encoding, unlike the case-preserving selector mangling.
      let helper = "guardedSend_" & mangleClass(choice.owner) & "_" & mangleSlot(selector)
      directCandidates[selector] = helper
      if choice.slot.len == 0:
        output.add(fmt("proc {choice.target}*(self: NodeValue, args: seq[NodeValue]): NodeValue\n"))
      output.add(fmt("var {helper}_class {{.threadvar.}}: Class\n"))
      output.add(fmt("var {helper}_guard {{.threadvar.}}: CompiledDirectGuard\n"))
      output.add(fmt("proc {helper}(owner, receiver: NodeValue): NodeValue {{.inline.}} =\n"))
      output.add(fmt("  if {helper}_class == nil: {helper}_class = compiledClassValue(\"{choice.owner}\").classVal\n"))
      output.add(fmt("  if canDirectCompiledSend(receiver, {helper}_class, \"{selector}\", {choice.target}, {helper}_guard):\n"))
      if choice.slot.len > 0:
        let read = mangleClass(choice.owner) & "_direct_" & mangleSlot(choice.slot) & "_read"
        output.add(fmt("    return {read}(receiver)\n"))
      else:
        output.add(fmt("    return {choice.target}(receiver, @[])\n"))
      output.add(fmt("  sendMessageBound(owner, receiver, \"{selector}\", @[])\n\n"))

  if not mixed:
    # Plan independently of source order, adding pure self-call chains only after
    # their callees have a native plan. Unique selectors keep routing conservative.
    var selectorCounts = initTable[string, int]()
    for md in methodDefs:
      selectorCounts[md.selector] = selectorCounts.getOrDefault(md.selector) + 1
    for owner in compiledClasses:
      var plans: IntegerPlans
      var planned: seq[int]
      for iteration in 0..<methodDefs.len:
        var changed = false
        for index, md in methodDefs:
          if md.className != owner or md.isClassMethod or index in planned or
             selectorCounts.getOrDefault(md.selector) != 1: continue
          let ownerClass = if owner in classInfo: classInfo[owner] else: nil
          let plan = planIntegerCall(owner, md.params, md.body, plans, md.temporaries,
                                     ownerClass)
          if not plan.eligible: continue
          let target = mangleClass(owner) & "_" & mangleSelector(md.selector)
          output.add(fmt("proc {target}*(self: NodeValue, args: seq[NodeValue]): NodeValue\n"))
          let emitted = emitIntegerCall(owner, md.selector, md.params, plan)
          output.add(emitted.code)
          integerCandidates[md.selector] = emitted.helper
          plans[md.selector] = plan
          planned.add(index)
          changed = true
        if not changed: break

  # Class-side Integer regions, usable from a call site with a literal class.
  var staticClassCalls = initTable[string, string]()
  if not mixed:
    var classSelectorCounts = initTable[string, int]()
    for md in methodDefs:
      if md.isClassMethod:
        classSelectorCounts[md.selector] = classSelectorCounts.getOrDefault(md.selector) + 1
    for md in methodDefs:
      if not md.isClassMethod or classSelectorCounts.getOrDefault(md.selector) != 1: continue
      let plan = planStaticClassCall(md.className, md.params, md.body, md.temporaries)
      if not plan.eligible: continue
      let emitted = emitStaticClassCall(md.className, md.selector, md.params, plan)
      output.add(emitted.code)
      let guardName = "guardStatic_" & mangleClass(md.className) & "_" & mangleSlot(md.selector)
      let target = mangleClass(md.className) & "_class_" & mangleSelector(md.selector)
      # Exact class object + unchanged class-method registration. Any override or
      # replacement flips the guard, and the call site keeps the ordinary send.
      # The guard compares against the registered proc, which is defined with
      # the rest of the compiled methods later in the module.
      output.add(fmt("proc {target}*(self: NodeValue, args: seq[NodeValue]): NodeValue\n"))
      output.add(fmt("var {guardName}_version {{.threadvar.}}: uint64\n"))
      output.add(fmt("var {guardName}_valid {{.threadvar.}}: bool\n"))
      output.add(fmt("proc {guardName}(): bool {{.inline.}} =\n"))
      output.add(fmt("  if {guardName}_version != compiledClassDispatchVersion:\n"))
      output.add(fmt("    {guardName}_valid = resolveCompiledClassMethod(\"{md.className}\", \"{md.selector}\") == {target}\n"))
      output.add(fmt("    {guardName}_version = compiledClassDispatchVersion\n"))
      output.add(fmt("  {guardName}_valid\n\n"))
      staticClassCalls[md.className & ">>" & md.selector] = emitted.nativeName


  output.add("\n# Compiled Methods\n")
  output.add("##################\n\n")
  
  for md in methodDefs:
    let clsName = md.className
    let selector = md.selector
    let params = md.params
    let body = md.body
    
    # Skip if class not in compiled classes
    if clsName notin compiledClasses:
      continue
    
    let mangledClass = mangleClass(clsName)
    let mangledSelector = mangleSelector(selector)
    let sidePrefix = if md.isClassMethod: "class_" else: ""
    let procName = fmt("{mangledClass}_{sidePrefix}{mangledSelector}")
    
    output.add(fmt("proc {procName}*(self: NodeValue, args: seq[NodeValue]): NodeValue =\n"))

    let methodCellNames = scopeCaptureCellNames(body, params & md.temporaries)
    for i, paramName in params:
      let paramValue = fmt("(if args.len > {i}: args[{i}] else: NodeValue(kind: vkNil))")
      let identifier = mangleIdentifier(paramName)
      if paramName in methodCellNames:
        output.add(fmt("  var {identifier} = MutableCell(value: {paramValue})\n"))
      else:
        output.add(fmt("  var {identifier} = {paramValue}\n"))
    
    if body.len > 0:
      var genCtx = newGenContext(nil, compiledClasses, classInfo)
      for globalName in knownGlobals:
        if globalName notin genCtx.globals:
          genCtx.globals.add(globalName)
      genCtx.inMethod = true
      genCtx.directSendCandidates = directCandidates
      genCtx.integerSendCandidates = integerCandidates
      genCtx.staticClassCalls = staticClassCalls

      genCtx.cellNames = methodCellNames
      if blockReg != nil:
        genCtx.blockRegistry = blockReg
      
      if clsName in classInfo:
        genCtx.cls = classInfo[clsName]
        # Only numeric candidates for *this* class; guards make them safe.
        for slotName in classInfo[clsName].getAllSlots().mapIt(it.name):
          let key = clsName & "#" & slotName
          if key in inferredNumeric:
            case inferredNumeric[key]
            of "skInt": genCtx.inferredNumericSlots[slotName] = nrInt
            of "skFloat": genCtx.inferredNumericSlots[slotName] = nrFloat
            else: discard
      
      genCtx.globals.add("self")
      genCtx.setVariableType("self", clsName, true)
      for paramName in params:
        genCtx.parameters.add(paramName)

      if not mixed and md.temporaries.len > 0:
        genCtx.numericBindings = analyzeNumericBindings(body, methodCellNames & params,
                                                       md.temporaries)
      output.add(indentBlock(genLocalDeclarations(genCtx, md.temporaries)))

      # If any nested block performs a non-local return (^), the method
      # boundary must catch NonLocalReturnException and return its value.
      var needsNLRWrapper = false
      for stmt in body:
        if hasBlocksWithNonLocalReturn(stmt):
          needsNLRWrapper = true
          break
      var hasHomeBlocks = false
      if blockReg != nil:
        for info in blockReg.blocks:
          if info.ownerMethodId == md.methodId:
            hasHomeBlocks = true
            break
      if hasHomeBlocks:
        output.add("  let hardingHome = CompiledReturnTarget(active: true)\n")
        output.add("  try:\n")
      
      for stmt in body:
        let stmtCode = genStatement(genCtx, stmt)
        if stmtCode.len > 0:
          for line in stmtCode.splitLines():
            if hasHomeBlocks:
              output.add("    " & line)
            else:
              output.add("  " & line)
            output.add("\n")

      # Explicit returns are emitted by genStatement; falling through answers self.
      if body[^1].kind != nkReturn:
        output.add(if hasHomeBlocks: "    return self\n" else: "  return self\n")
      
      if needsNLRWrapper:
        # Only consume non-local returns that target this method; let
        # returns aimed at outer methods continue unwinding.
        output.add("  except NonLocalReturnException as nlr:\n")
        output.add("    if nlr.target == hardingHome:\n")
        output.add("      return nlr.value\n")
        output.add("    raise\n")
      if hasHomeBlocks:
        output.add("  finally:\n")
        output.add("    hardingHome.active = false\n")
    else:
      output.add("  return self\n")
    
    output.add("\n\n")
    
    # Add registration call
    let registrationProc = if md.isClassMethod: "registerCompiledClassMethod" else: "registerCompiledMethod"
    registrationCode.add(fmt("  {registrationProc}(\"{clsName}\", \"{selector}\", {procName})\n"))
    # Interpreted-to-compiled shim. Class and selector are baked in so the
    # interpreter can reach this body without inspecting the running activation.
    let shimName = fmt("shim_{mangledClass}_{sidePrefix}{mangledSelector}")
    let receiverType = if md.isClassMethod: "NodeValue" else: "Instance"
    let receiverValue = if md.isClassMethod: "self" else: "NodeValue(kind: vkInstance, instVal: self)"
    let classSide = if md.isClassMethod: "true" else: "false"
    output.add(fmt("proc {shimName}*(interp: var Interpreter, self: {receiverType}, args: seq[NodeValue]): NodeValue {{.nimcall.}} =\n"))
    output.add(fmt("  ## Interpreted-to-compiled entry point for {clsName}>>{selector}\n"))
    output.add("  initRuntime()\n")
    output.add(fmt("  {procName}({receiverValue}, args)\n\n"))
    shimBindingCode.add(fmt("  discard bindCompiledMethodShim(interp, \"{clsName}\", \"{selector}\", cast[pointer]({shimName}), isClassMethod = {classSide})\n"))
  
  # Generate slot accessor registrations for all compiled classes
  var slotRegCode = ""
  for clsName in compiledClasses:
    if clsName in classInfo:
      slotRegCode.add(genSlotAccessorRegistrations(classInfo[clsName]))

  # Add registration procs (stubs if no methods/superclasses)
  output.add("# Method Registration\n")
  output.add("#####################\n\n")
  output.add("proc registerCompiledMethods*() =\n")
  for className in compiledClasses:
    output.add(fmt("  registerCompiledSlotNames(\"{className}\", @[])\n"))
  if registrationCode.len > 0 or slotRegCode.len > 0:
    output.add(registrationCode)
    output.add(slotRegCode)
  else:
    output.add("  discard 0\n")
  output.add("\n")

  # Interpreted-to-compiled binding. The host calls this once an interpreter is
  # live (mixed mode or an embedded host); pure compiled programs simply skip it.
  output.add("proc bindCompiledMethodsTo*(interp: var Interpreter) =\n")
  if shimBindingCode.len > 0:
    output.add(shimBindingCode)
  else:
    output.add("  discard\n")
  output.add("\n")

  return output

proc isHardingCompileBlock(node: Node): bool =
  ## Check if node is "Harding compile: [block]"
  if node.kind != nkMessage:
    return false
  let msg = node.MessageNode
  if msg.selector != "compile:":
    return false
  if msg.receiver == nil or msg.receiver.kind != nkIdent:
    return false
  return msg.receiver.IdentNode.name == "Harding"

proc isHardingMainBlock(node: Node): bool =
  ## Check if node is "Harding main: [block]"
  if node.kind != nkMessage:
    return false
  let msg = node.MessageNode
  if msg.selector != "main:":
    return false
  if msg.receiver == nil or msg.receiver.kind != nkIdent:
    return false
  return msg.receiver.IdentNode.name == "Harding"

proc extractHardingBlocks(nodes: seq[Node]): tuple[compileBlock, mainBlock: BlockNode, other: seq[Node]] =
  ## Extract Harding compile: and main: blocks from nodes
  result = (nil, nil, @[])
  
  for node in nodes:
    if node.isHardingCompileBlock:
      if node.MessageNode.arguments.len > 0 and node.MessageNode.arguments[0].kind == nkBlock:
        result.compileBlock = node.MessageNode.arguments[0].BlockNode
    elif node.isHardingMainBlock:
      if node.MessageNode.arguments.len > 0 and node.MessageNode.arguments[0].kind == nkBlock:
        result.mainBlock = node.MessageNode.arguments[0].BlockNode
    else:
      result.other.add(node)

proc collectTopLevelGlobals*(nodes: seq[Node]): seq[string] =
  ## Names assigned at top level whose first letter is uppercase are Harding
  ## globals (matching the interpreter's uppercase-means-global rule). They are
  ## emitted as module-level shared bindings rather than locals of main(), so
  ## methods and blocks observe the same value.
  var names: seq[string]
  var seen = initHashSet[string]()
  proc walk(node: Node) =
    if node == nil: return
    case node.kind
    of nkAssign:
      let name = node.AssignNode.variable
      if name.len > 0 and name[0] in {'A'..'Z'} and name notin seen:
        seen.incl(name)
        names.add(name)
      walk(node.AssignNode.expression)
    of nkSlotAccess, nkNamedAccess:
      # A class-side initializer may publish a global through a slot-like store,
      # e.g. `JsonNULL := self new initializeWith: "null"`. Its reads elsewhere
      # must resolve to that global instead of a symbol literal.
      let assignment = if node.kind == nkSlotAccess: node.SlotAccessNode.isAssignment
                       elif node.kind == nkNamedAccess: node.NamedAccessNode.isAssignment
                       else: false
      let valueExpr = if node.kind == nkSlotAccess: node.SlotAccessNode.valueExpr
                      else: node.NamedAccessNode.valueExpr
      if assignment and valueExpr != nil: walk(valueExpr)
    of nkMessage:
      walk(node.MessageNode.receiver)
      for argument in node.MessageNode.arguments: walk(argument)
    of nkBlock:
      for statement in node.BlockNode.body: walk(statement)
    of nkLiteral:
      # Method bodies arrive as block literals, so a global published from one
      # is only found by walking into the literal's block value.
      let value = node.LiteralNode.value
      if value.kind == vkBlock and value.blockVal != nil:
        for statement in value.blockVal.body: walk(statement)
    of nkIf:
      walk(node.IfNode.condition)
      walk(node.IfNode.thenBranch)
      walk(node.IfNode.elseBranch)
    of nkWhile:
      walk(node.WhileNode.condition)
      walk(node.WhileNode.body)
    of nkReturn:
      walk(node.ReturnNode.expression)
    of nkCascade:
      walk(node.CascadeNode.receiver)
      for message in node.CascadeNode.messages: walk(message)
    of nkSuperSend:
      for argument in node.SuperSendNode.arguments: walk(argument)
    else: discard
  for node in nodes:
    walk(node)
  result = names

proc genMainProc*(ctx: var CompilerContext, topLevel: seq[Node], moduleName: string,
                  blockReg: BlockRegistry = nil, compiledClasses: seq[string] = @[],
                  classInfo: Table[string, ClassInfo] = initTable[string, ClassInfo](),
                  mixed: bool = false, sourceFile: string = "",
                  injectMainArgsVar: bool = false,
                  knownGlobals: seq[string] = @[],
                  temporaries: seq[string] = @[],
                  integerCandidates: Table[string, string] = initTable[string, string](),
                  staticClassCalls: Table[string, string] = initTable[string, string]()): string =
  ## Generate the main() procedure for top-level statement execution
  var output = ""

  output.add("# Main Entry Point\n")
  output.add("##################\n\n")

  output.add("proc main(): int =\n")
  output.add("  ## Main entry point for ")
  output.add(moduleName)
  output.add("\n")

  # Initialize runtime
  output.add("  initRuntime()\n")
  output.add("  registerCompiledMethods()\n")
  output.add("  registerSuperclassHierarchy()\n")
  for className in compiledClasses:
    let nativeClass = mangleClass(className)
    output.add(fmt("  registerCompiledClass(\"{className}\", allocate{nativeClass})\n"))
  output.add("\n")
  if ctx.gtkApplication:
    output.add("  registerNativeGtk()\n")

  if ctx.sealedClasses.len > 0:
    # Finish lazy built-in hierarchy setup before sealing the native registry.
    output.add("  discard compiledBaseClassValue(\"Object\")\n")
    for name in ctx.sealedClasses:
      output.add(fmt("  sealCompiledClass(\"{name}\")\n"))

  # If mixed mode, initialize hybrid runtime with source file
  if mixed and sourceFile.len > 0:
    output.add(fmt("  initHybridRuntime(@[\"{sourceFile}\"])\n\n"))

  if injectMainArgsVar:
    output.add("  var hardingArgsElems: seq[NodeValue] = @[]\n")
    output.add("  for arg in commandLineParams():\n")
    output.add("    hardingArgsElems.add(NodeValue(kind: vkString, strVal: arg))\n")
    output.add(fmt("  var {mangleIdentifier(\"args\")} {{.used.}} = NodeValue(kind: vkArray, arrayVal: hardingArgsElems)\n\n"))

  # Create generation context for top-level code, sharing block registry if provided
  var genCtx = newGenContext(nil, compiledClasses, classInfo, mixed)
  genCtx.integerSendCandidates = integerCandidates
  genCtx.staticClassCalls = staticClassCalls
  for globalName in knownGlobals:
    if globalName notin genCtx.globals:
      genCtx.globals.add(globalName)
  if injectMainArgsVar:
    genCtx.locals.add("args")
    genCtx.globals.add("args")
  if blockReg != nil:
    genCtx.blockRegistry = blockReg
  genCtx.cellNames = scopeCaptureCellNames(topLevel)
  if not mixed:
    genCtx.numericBindings = analyzeNumericBindings(topLevel, genCtx.cellNames & temporaries)

  # Run top-level work under an uncaught-error barrier so a compiled error
  # follows the Harding default-action/diagnostic path instead of escaping as a
  # Nim exception.
  output.add("  try:\n")
  output.add(indentBlock(genLocalDeclarations(genCtx, temporaries), 4))
  for node in topLevel:
    let stmtCode = genTopLevelStatement(genCtx, node)
    if stmtCode.len > 0:
      # Indent the statement
      for line in stmtCode.splitLines():
        output.add("    ")
        output.add(line)
        output.add("\n")

  # Return exit code 0
  output.add("\n    return 0\n")
  output.add("  except CompiledHardingError as failure:\n")
  output.add("    return reportUncaughtError(failure.value)\n")
  # A Nim Defect from native arithmetic (overflow, index error) has no Harding
  # error value. Report it in the interpreter's diagnostic shape instead of
  # leaking a Nim traceback; explicit Harding errors keep the path above.
  output.add("  except Defect as failure:\n")
  output.add("    return reportUncaughtDefect(failure.msg)\n")

  return output

proc genModule*(ctx: var CompilerContext, nodes: seq[Node],
                moduleName: string, mixed: bool = false, sourceFile: string = "",
                reflectedClasses: Table[string, ClassInfo] = initTable[string, ClassInfo](),
                injectMainArgsVar: bool = false,
                scriptTemporaries: seq[string] = @[],
                inferredNumeric: Table[string, string] = initTable[string, string](),
                prebuiltClasses: Table[string, ClassInfo] = initTable[string, ClassInfo]()): string =
  ## Generate complete Nim module from parsed nodes
  ## mixed: if true, embed interpreter for fallback on unsupported features
  ## sourceFile: path to source .hrd file for class registration in interpreter
  ## reflectedClasses: optional class info from interpreter execution (for dynamic classes)
  var output = ""

  output.add(genModuleHeader(ctx, moduleName, includeOsImport = injectMainArgsVar))

  # Extract Harding compile: and main: blocks first
  let hardingBlocks = nodes.extractHardingBlocks()
  
  # Determine what to compile as main:
  # If there's a Harding main: block, use its body; otherwise use top-level code.
  var mainBodyNodes: seq[Node]
  if hardingBlocks.mainBlock != nil:
    mainBodyNodes = hardingBlocks.mainBlock.body
  else:
    # Use everything that's not a compile block
    mainBodyNodes = hardingBlocks.other

  # Build the definition source used for class/method extraction.
  # compile: contributes definitions for codegen but does NOT run at runtime in generated main().
  var defsSourceNodes = mainBodyNodes
  if hardingBlocks.compileBlock != nil:
    defsSourceNodes = hardingBlocks.compileBlock.body & defsSourceNodes

  let (classDefs, _) = extractClassAndMethodDefs(defsSourceNodes)
  let (_, executableMainNodes) = extractClassAndMethodDefs(mainBodyNodes)

  # Top-level uppercase names are Harding globals: module-level shared bindings
  # that main(), methods and blocks all resolve to.
  let mainTemporaries = if hardingBlocks.mainBlock != nil:
                          hardingBlocks.mainBlock.temporaries
                        else: scriptTemporaries
  var knownGlobals: seq[string] = @[]
  for name in collectTopLevelGlobals(executableMainNodes):
    if name notin mainTemporaries:
      knownGlobals.add(name)
  # Uppercase names are globals wherever they are assigned, matching the
  # interpreter's rule. A class-side initializer such as
  # `JsonLiteral class>>initialize [ JsonNULL := ... ]` publishes a global that
  # other methods read; scanning only top-level code left those reads resolving
  # to a symbol literal instead of the stored value.
  for name in collectTopLevelGlobals(defsSourceNodes):
    if name notin mainTemporaries and name notin knownGlobals:
      knownGlobals.add(name)

  # Analyze classes from AST and optionally enrich slots from reflected runtime classes.
  # This avoids pulling unrelated stdlib/internal classes into generated output.
  # Reuse the caller's class model when it has one: rebuilding here would discard
  # decisions already applied to it (observed-type narrowing, reflected layout).
  let analysis = if prebuiltClasses.len > 0:
                   AnalysisResult(classes: prebuiltClasses)
                 else:
                   buildClassModel(defsSourceNodes, reflectedClasses)
  # Collect compiled class names for native instantiation
  var compiledClassNames: seq[string] = @[]
  for cls in analysis.classes.values:
    compiledClassNames.add(cls.name)

  # Extract method definitions from class and compile blocks
  let methodDefs = extractMethodDefs(classDefs)

  # Create the shared block registry early so method bodies and main() both
  # register blocks into the same registry (unique names, shared procedures).
  var blockReg = newBlockRegistry()

  # Note: top-level variables are NOT passed as knownGlobals because they are
  # locals of main() and need to be captured by block procs at module level.
  # Only true globals (class names) would be excluded from captures.
  for md in methodDefs:
    var ownerSlots: seq[string] = @[]
    if md.className in analysis.classes:
      for slot in analysis.classes[md.className].getAllSlots():
        ownerSlots.add(slot.name)
    # Parameters and temporaries shadow same-named slots for blocks in the body.
    var ownerLocals: seq[string] = @[]
    for p in md.params:
      ownerLocals.add(p)
    for t in md.temporaries:
      ownerLocals.add(t)
    for stmt in md.body:
      collectBlocks(blockReg, stmt, knownGlobals & compiledClassNames & uppercaseReferences(stmt),
                    ownerSlots, ownerLocals)
  # Stamp method ownership so ^ inside these blocks targets the right method.
  # Walk the registry once per method, matching block nodes by identity against
  # the method body's registered nodes.
  for md in methodDefs:
    var bodyNodes = initTable[pointer, bool]()
    for stmt in md.body:
      collectAstNodes(bodyNodes, stmt)
    for info in blockReg.blocks.mitems:
      if info.ownerMethodId == 0 and cast[pointer](info.blockNode) in bodyNodes:
        info.ownerMethodId = md.methodId
        # Method-owned closures retain their receiver for allocation routing,
        # even if no source expression explicitly references self.
        if "self" notin info.captures:
          info.captures.add("self")
          info.captureTypes.add("MutableCell")

  # Generate for each class
  for cls in analysis.classes.values:
    output.add(genClassConstants(cls))
    output.add(genSlotAccessors(cls))
    output.add(genClassInit(cls))
    let nativeClass = mangleClass(cls.name)
    output.add(fmt("proc allocate{nativeClass}(self: NodeValue, args: seq[NodeValue]): NodeValue =\n"))
    output.add(fmt("  new{nativeClass}().toValue()\n\n"))
    output.add(fmt("var allocationVersion_{nativeClass} {{.threadvar.}}: uint64\n"))
    output.add(fmt("var directAllocation_{nativeClass} {{.threadvar.}}: bool\n"))
    output.add(fmt("proc guardedNew_{nativeClass}(ownerReceiver: NodeValue = NodeValue(kind: vkNil)): NodeValue =\n"))
    output.add(fmt("  let hostAllocation = boundNewInstance(ownerReceiver, \"{cls.name}\")\n"))
    output.add("  if hostAllocation.handled:\n    return hostAllocation.value\n")
    output.add(fmt("  if allocationVersion_{nativeClass} != compiledClassDispatchVersion:\n"))
    output.add(fmt("    directAllocation_{nativeClass} = canDirectAllocate(\"{cls.name}\", allocate{nativeClass})\n"))
    output.add(fmt("    allocationVersion_{nativeClass} = compiledClassDispatchVersion\n"))
    output.add(fmt("  if directAllocation_{nativeClass}:\n"))
    output.add(fmt("    return compiledNewInstance(\"{cls.name}\", allocate{nativeClass})\n"))
    output.add(fmt("  return sendMessage(currentRuntime[], compiledClassValue(\"{cls.name}\"), \"new\", @[])\n\n"))

  # Generate superclass hierarchy registration
  var superclassCalls = ""

  # Static inheritance from class analysis (derive:, deriveWithAccessors:)
  for cls in analysis.classes.values:
    if cls.parent != nil and cls.parent.name.len > 0:
      superclassCalls.add(fmt("  registerSuperclass(\"{cls.name}\", \"{cls.parent.name}\")\n"))

  # Static inheritance from derive receiver (includes parents outside compiled set, e.g. Object)
  for node in classDefs:
    let (className, parentName, _) = extractDeriveChain(node)
    if className.len > 0 and parentName.len > 0 and className != parentName:
      superclassCalls.add(fmt("  registerSuperclass(\"{className}\", \"{parentName}\")\n"))

  # Dynamic inheritance from explicit addSuperclass: calls
  for node in mainBodyNodes:
    if node.kind == nkMessage:
      let msg = node.MessageNode
      if msg.selector == "addSuperclass:" and msg.arguments.len >= 1:
        if msg.receiver != nil and msg.receiver.kind == nkIdent:
          let subclassName = msg.receiver.IdentNode.name
          if msg.arguments[0].kind == nkIdent:
            let superclassName = msg.arguments[0].IdentNode.name
            superclassCalls.add(fmt("  registerSuperclass(\"{subclassName}\", \"{superclassName}\")\n"))
  
  if superclassCalls.len > 0:
    output.add("\n")
    output.add("# Superclass Hierarchy\n")
    output.add("######################\n\n")
    output.add("proc registerSuperclassHierarchy*() =\n")
    output.add(superclassCalls)
    output.add("\n")
  else:
    output.add("proc registerSuperclassHierarchy*() = discard 0\n\n")

  # Collect blocks from top-level code into the shared registry
  let mainLocals = scopeLocalNames(executableMainNodes, mainTemporaries)
  for node in mainBodyNodes:
    collectBlocks(blockReg, node, knownGlobals, ownerLocalNames = mainLocals)

  # Generate block environment structs and forward declarations BEFORE the
  # compiled methods so method bodies can reference block procedures.
  output.add("\n")
  output.add("# Block Environment Structs\n")
  output.add("#########################\n\n")
  for blockInfo in blockReg.getAllBlocks():
    let structDef = generateEnvStructDef(blockInfo)
    if structDef.len > 0:
      output.add(structDef)
      output.add("\n\n")

  output.add("# Block Forward Declarations\n")
  output.add("############################\n\n")
  for blockInfo in blockReg.getAllBlocks():
    output.add(generateBlockProcSignature(blockInfo))
    output.add("\n")
  output.add("\n")

  # Generate compiled methods from user definitions after primitive operators,
  # so compiled method bodies can call nt_* helpers without forward declarations.
  var integerCandidates = initTable[string, string]()
  var staticClassCalls = initTable[string, string]()
  output.add(genCompiledMethods(methodDefs, compiledClassNames, analysis.classes, blockReg,
                                knownGlobals, mixed, inferredNumeric, integerCandidates,
                                staticClassCalls))

  # Generate block procedure definitions (after primitives so they can reference them)
  output.add("\n")
  output.add("# Block Procedures\n")
  output.add("##################\n\n")

  # Generate block procedure bodies using real code generation
  var blockGenCtx = newGenContext(nil, compiledClassNames, analysis.classes, mixed)
  for globalName in knownGlobals:
    if globalName notin blockGenCtx.globals:
      blockGenCtx.globals.add(globalName)
  blockGenCtx.blockRegistry = blockReg  # Share the registry so nested blocks can be found
  for blockInfo in blockReg.getAllBlocks():
    output.add(generateBlockProcSignature(blockInfo))
    output.add(" =\n")
    # ^ inside a block always escapes to the home method: raise so the
    # compiled method boundary can catch it (unless the block IS the method
    # body itself, in which case a plain return is correct).
    # Blocks lexically inside compiled methods must use method-context code
    # (getSlotValue/setSlotValue on self as NodeValue), not top-level access.
    blockGenCtx.inMethod = blockInfo.ownerMethodId != 0
    blockGenCtx.cls = nil
    for md in methodDefs:
      if md.methodId == blockInfo.ownerMethodId and md.className in analysis.classes:
        blockGenCtx.cls = analysis.classes[md.className]
        break
    let body = genBlockBody(blockGenCtx, blockInfo.blockNode, blockInfo.captures,
                            not blockInfo.homeInMethod, blockInfo.envStructName,
                            blockInfo.ownerMethodId)
    if body.len > 0:
      output.add(body)
    else:
      output.add("  return NodeValue(kind: vkNil)\n")
    output.add("\n\n")

  if ctx.frozenHostSources.len > 0:
    output.add("proc newFrozenHost*(): SchedulerContext =\n")
    output.add("  ## Embedded library host; application statements are not replayed.\n")
    output.add("  initRuntime()\n  registerCompiledMethods()\n  registerSuperclassHierarchy()\n")
    output.add("  result = newEmbeddedFrozenHost([\n")
    for (path, source) in ctx.frozenHostSources:
      output.add("    (\"" & escapeNimString(path) & "\", \"" & escapeNimString(source) & "\"),\n")
    output.add("  ])\n")
    output.add("  var interp = frozenHostInterpreter(result)\n")
    output.add("  bindCompiledMethodsTo(interp)\n\n")

  # Generate main proc for top-level statements, sharing block registry
  output.add(genMainProc(ctx, executableMainNodes, moduleName, blockReg, compiledClassNames,
                         analysis.classes, mixed, sourceFile, injectMainArgsVar,
                         knownGlobals, mainTemporaries, integerCandidates,
                         staticClassCalls))

  # Module initialization
  output.add("\n")
  output.add("# Module Initialization\n")
  output.add("######################\n")

  output.add(fmt("""
proc init_{moduleName}*() =
  ## Initialize {moduleName} module
  initRuntime()
  registerCompiledMethods()
  echo "Module loaded: {moduleName}"

when isMainModule:
  quit(main())
"""))

  return output

proc compileFile*(inputPath: string, outputDir = "./build"): string =
  ## Compile a Harding source file to Nim
  let source = readFile(inputPath)
  let tokens = lex(source)
  var parser = initParser(tokens)
  let script = parser.parseScript()
  let nodes = if script != nil: script.body else: @[]

  if parser.hasError:
    echo "Parse error: " & parser.errorMsg
    return ""

  let moduleName = inputPath.extractFilename().changeFileExt("")

  var ctx = newCompiler(outputDir, moduleName)
  let nimCode = genModule(ctx, nodes, moduleName, scriptTemporaries = script.temporaries)

  let outputPath = outputDir / moduleName & ".nim"
  createDir(outputDir)
  writeFile(outputPath, nimCode)

  return outputPath
